export type PhoneCountryCode = (typeof PHONE_COUNTRIES)[number]["code"];

const PHONE_COUNTRIES_BY_CODE = new Map<string, PhoneCountry>(
  PHONE_COUNTRIES.map((country) => [country.code, country])
);

export function getPhoneCountryByCode(code: string | null | undefined) {
  const normalizedCode = code?.trim().toUpperCase();
  if (!normalizedCode) return null;
  return PHONE_COUNTRIES_BY_CODE.get(normalizedCode) ?? null;
}

export const DEFAULT_PHONE_COUNTRY =
  getPhoneCountryByCode("VN") ??
  (() => {
    throw new Error("Default phone country VN is missing from PHONE_COUNTRIES");
  })();

function getRegionFromLocale(locale: string) {
  try {
    return new Intl.Locale(locale).region ?? null;
  } catch {
    const match = locale.match(/[-_]([A-Z]{2}|\d{3})\b/i);
    return match?.[1]?.toUpperCase() ?? null;
  }
}

export function detectCurrentPhoneCountry() {
  if (typeof navigator === "undefined") return DEFAULT_PHONE_COUNTRY;

  const locales = navigator.languages?.length ? navigator.languages : [navigator.language];
  for (const locale of locales) {
    const country = getPhoneCountryByCode(getRegionFromLocale(locale));
    if (country) return country;
  }

  return DEFAULT_PHONE_COUNTRY;
}
