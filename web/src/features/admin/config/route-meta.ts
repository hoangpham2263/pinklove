import { ROUTES } from "@/lib/routes";

export function getAdminPageTitle(pathname: string): string {
  if (pathname === ROUTES.ADMIN.ROOT || pathname.startsWith(ROUTES.ADMIN.DASHBOARD)) return "Dashboard";
  if (pathname.startsWith(ROUTES.ADMIN.GLOBAL_FIELDS)) return "Global Fields";
  if (pathname.startsWith(ROUTES.ADMIN.PAGES)) return "Pages";
  if (pathname.startsWith(ROUTES.ADMIN.BLOG)) return "Blog Posts";
  if (pathname.startsWith(ROUTES.ADMIN.BLOG_CATEGORIES)) return "Blog Categories";
  if (pathname.startsWith(ROUTES.ADMIN.MENUS)) return "Navigation";
  if (pathname.startsWith(ROUTES.ADMIN.OFFERING_TYPES)) return "Offering Types";
  if (pathname.startsWith(ROUTES.ADMIN.OFFERING_TEMPLATES)) return "Offering Templates";
  if (pathname.startsWith(ROUTES.ADMIN.OFFERING_BUILDER)) return "Offering Builder";
  if (pathname.startsWith(ROUTES.ADMIN.PROVIDER_OFFERINGS)) return "Provider Offering Review";
  if (pathname.startsWith(ROUTES.ADMIN.OFFERING_CATEGORIES)) return "Offering Categories";
  if (pathname === ROUTES.ADMIN.OFFERINGS) return "Create Offering";
  if (pathname === ROUTES.ADMIN.OFFERING_MANAGE) return "Offering";
  if (pathname.startsWith(`${ROUTES.ADMIN.OFFERING_LIST}/`)) return "Edit Offering";
  if (pathname === ROUTES.ADMIN.OFFERING_LIST) return "Offerings Overview";
  if (pathname.startsWith(ROUTES.ADMIN.ORDERS)) return "Orders";
  if (pathname.startsWith(ROUTES.ADMIN.PAYMENTS)) return "Payments";
  if (pathname.startsWith(ROUTES.ADMIN.SHIPMENTS)) return "Shipments";
  if (pathname.startsWith(ROUTES.ADMIN.USERS)) return "Users";
  if (pathname.startsWith(ROUTES.ADMIN.CUSTOMERS)) return "Khách hàng";
  if (pathname.startsWith(ROUTES.ADMIN.AFFILIATE_USERS)) return "Đối tác / CTV";
  if (pathname.startsWith(ROUTES.ADMIN.PROVIDER_ACCOUNTS)) return "Nhà cung cấp";
  if (pathname.startsWith(ROUTES.ADMIN.INTERNAL_ACCOUNTS)) return "Tài khoản nội bộ";
  if (pathname.startsWith(ROUTES.ADMIN.AFFILIATE_APPLICATIONS)) return "Hồ sơ Guest Affiliate";
  if (pathname.startsWith(ROUTES.ADMIN.AFFILIATE_ACCOUNTS)) return "Duyệt Customer Affiliate";
  if (pathname.startsWith(ROUTES.ADMIN.AFFILIATE_CONVERSIONS)) return "Hoa hồng Affiliate";
  if (pathname.startsWith(ROUTES.ADMIN.AFFILIATES)) return "Affiliate Overview";
  if (pathname.startsWith(ROUTES.ADMIN.MEDIA)) return "Media";
  if (pathname.startsWith(ROUTES.ADMIN.COMMENTS)) return "Comments";
  if (pathname.startsWith(ROUTES.ADMIN.NOTIFICATIONS)) return "Thông báo";
  if (pathname.startsWith(ROUTES.ADMIN.SEO_PAGES)) return "Page SEO";
  if (pathname.startsWith(ROUTES.ADMIN.SEO_SCHEMA)) return "SEO Schema";
  if (pathname.startsWith(ROUTES.ADMIN.SEO_RULES)) return "SEO Rules";
  if (pathname.startsWith(ROUTES.ADMIN.SEO_GUIDE)) return "Page SEO";
  if (pathname.startsWith(ROUTES.ADMIN.CONFIG_PAYMENT_METHODS)) return "Payment Methods";
  if (pathname.startsWith(ROUTES.ADMIN.CONFIG_SHIPPING)) return "Shipping";
  if (pathname.startsWith(ROUTES.ADMIN.CONFIG_ECOMMERCE)) return "Ecommerce Connections";
  if (pathname.startsWith(ROUTES.ADMIN.CONFIG_THIRD_PARTY)) return "Đăng nhập bên thứ 3";
  if (pathname.startsWith(ROUTES.ADMIN.CONFIG_SEO_REDIRECTS)) return "SEO Redirects";
  if (pathname.startsWith(ROUTES.ADMIN.CONFIG_SITEMAP_SETTINGS)) return "Sitemap Settings";
  if (pathname.startsWith(ROUTES.ADMIN.CONFIG_SITEMAP_INDEX)) return "Sitemap Index";
  if (pathname.startsWith(ROUTES.ADMIN.CONFIG_INTERNAL_API_OFFERINGS)) return "API Import Sản phẩm";
  if (pathname.startsWith(ROUTES.ADMIN.CONFIG_INTERNAL_APIS)) return "API nội bộ";
  if (pathname.startsWith(ROUTES.ADMIN.CONFIG_BACKUPS)) return "Backups";
  if (pathname.startsWith(ROUTES.ADMIN.HOOKS)) return "Hooks";
  if (pathname.startsWith(ROUTES.ADMIN.CONFIG)) return "Cấu hình";
  return "Admin";
}
