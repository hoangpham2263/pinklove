import { ROUTES } from "@/lib/routes";
import { ADMIN_FEATURES } from "@/features/admin/config/navigation";

export function getAdminPageTitle(pathname: string): string {
  const feature = ADMIN_FEATURES.find((entry) => entry.href === pathname);
  if (feature) return feature.label;

  if (pathname === ROUTES.ADMIN.ROOT || pathname.startsWith(ROUTES.ADMIN.DASHBOARD)) return "Dashboard";
  if (pathname.startsWith(ROUTES.ADMIN.GLOBAL_FIELDS)) return "Global Fields";
  if (pathname.startsWith(ROUTES.ADMIN.PAGES)) return "Pages";
  if (pathname.startsWith(ROUTES.ADMIN.BLOG_CATEGORIES)) return "Blog Categories";
  if (pathname.startsWith(ROUTES.ADMIN.BLOG_POSTS)) return "Blog Posts";
  if (pathname.startsWith(ROUTES.ADMIN.BLOG)) return "Blog";
  if (pathname.startsWith(ROUTES.ADMIN.MENUS)) return "Navigation";
  if (pathname.startsWith(ROUTES.ADMIN.OFFERING_TYPES)) return "Offering Types";
  if (pathname.startsWith(ROUTES.ADMIN.OFFERING_TEMPLATES)) return "Offering Templates";
  if (pathname.startsWith(ROUTES.ADMIN.OFFERING_BUILDER)) return "Offering Builder";
  if (pathname.startsWith(ROUTES.ADMIN.PROVIDER_OFFERINGS)) return "Duyệt yêu cầu dịch vụ/sản phẩm provider";
  if (pathname.startsWith(ROUTES.ADMIN.OFFERING_CATEGORIES)) return "Offering Categories";
  if (pathname === ROUTES.ADMIN.OFFERINGS) return "Create Offering";
  if (pathname === ROUTES.ADMIN.OFFERING_LIST) return "Offerings Overview";
  if (pathname.startsWith(ROUTES.ADMIN.ORDERS)) return "Orders";
  if (pathname.startsWith(ROUTES.ADMIN.BOOKINGS)) return "Bookings";
  if (pathname.startsWith(ROUTES.ADMIN.PAYMENTS)) return "Payments";
  if (pathname.startsWith(ROUTES.ADMIN.SHIPMENTS)) return "Shipments";
  if (pathname.startsWith(ROUTES.ADMIN.USERS)) return "Users";
  if (pathname.startsWith(ROUTES.ADMIN.CUSTOMERS)) return "Khách hàng";
  if (pathname.startsWith(ROUTES.ADMIN.AFFILIATE_USERS)) return "Đối tác / CTV";
  if (pathname.startsWith(ROUTES.ADMIN.PROVIDER_ACCOUNTS)) return "Nhà cung cấp";
  if (pathname.startsWith(ROUTES.ADMIN.PROVIDER_REVIEWS)) return "Provider Reviews";
  if (pathname.startsWith(ROUTES.ADMIN.INTERNAL_ACCOUNTS)) return "Tài khoản nội bộ";
  if (pathname.startsWith(ROUTES.ADMIN.ACCESS_ROLES)) return "Access Roles";
  if (pathname.startsWith(ROUTES.ADMIN.AFFILIATE_APPLICATIONS)) return "Hồ sơ Guest Affiliate";
  if (pathname.startsWith(ROUTES.ADMIN.AFFILIATE_ACCOUNTS)) return "Duyệt Customer Affiliate";
  if (pathname.startsWith(ROUTES.ADMIN.AFFILIATE_CONVERSIONS)) return "Hoa hồng Affiliate";
  if (pathname.startsWith(ROUTES.ADMIN.AFFILIATES)) return "Affiliate Overview";
  if (pathname.startsWith(ROUTES.ADMIN.MEDIA_LIBRARY)) return "Media Library";
  if (pathname.startsWith(ROUTES.ADMIN.MEDIA_COLLECTIONS)) return "Media Collections";
  if (pathname.startsWith(ROUTES.ADMIN.MEDIA)) return "Media";
  if (pathname.startsWith(ROUTES.ADMIN.AUDIT_LOGS)) return "Audit Logs";
  if (pathname.startsWith(ROUTES.ADMIN.MARKETING_CAMPAIGNS)) return "Campaigns";
  if (pathname.startsWith(ROUTES.ADMIN.AB_EXPERIMENTS)) return "A/B Tests";
  if (pathname.startsWith(ROUTES.ADMIN.ANALYTICS_EVENTS)) return "Conversion/Event Analytics";
  if (pathname.startsWith(ROUTES.ADMIN.ANALYTICS_GOALS)) return "Analytics Goals";
  if (pathname.startsWith(ROUTES.ADMIN.COMMENTS)) return "Comments";
  if (pathname.startsWith(ROUTES.ADMIN.NOTIFICATIONS)) return "Thông báo";
  if (pathname.startsWith(ROUTES.ADMIN.SEO_PAGES)) return "Page SEO";
  if (pathname.startsWith(ROUTES.ADMIN.SEO_SCHEMA)) return "SEO Schema";
  if (pathname.startsWith(ROUTES.ADMIN.SEO_RULES)) return "SEO Rules";
  if (pathname.startsWith(ROUTES.ADMIN.CONFIG_BREADCRUMBS)) return "Breadcrumbs";
  if (pathname.startsWith(ROUTES.ADMIN.CONFIG_OPENGRAPH)) return "Open Graph";
  if (pathname.startsWith(ROUTES.ADMIN.CONFIG_SITEMAP_SETTINGS)) return "Sitemap Settings";
  if (pathname.startsWith(ROUTES.ADMIN.CONFIG_SITEMAP_INDEX)) return "Sitemap Index";
  if (pathname.startsWith(ROUTES.ADMIN.CONFIG_SEO_REDIRECTS)) return "SEO Redirects";
  if (pathname.startsWith(ROUTES.ADMIN.CONFIG_SEO)) return "SEO Management";
  if (pathname.startsWith(ROUTES.ADMIN.SECURITY_SETTINGS_AUTH_RATE_LIMITS)) return "Auth Rate Limits";
  if (pathname.startsWith(ROUTES.ADMIN.SECURITY_SETTINGS_CSRF)) return "CSRF Protection";
  if (pathname.startsWith(ROUTES.ADMIN.SECURITY_SETTINGS_HEADERS)) return "Security Headers";
  if (pathname.startsWith(ROUTES.ADMIN.SECURITY_SETTINGS_PROXY)) return "Proxy / IP Detection";
  if (pathname.startsWith(ROUTES.ADMIN.SECURITY_LOGS)) return "Security Logs";
  if (pathname.startsWith(ROUTES.ADMIN.SECURITY_BLOCKED_IPS)) return "Blocked IPs";
  if (pathname.startsWith(ROUTES.ADMIN.SECURITY_AUDIT_LOGS)) return "Security Audit Logs";
  if (pathname.startsWith(ROUTES.ADMIN.SECURITY_BACKUPS)) return "Backup/Restore Security";
  if (pathname.startsWith(ROUTES.ADMIN.SECURITY_UPLOAD)) return "Upload Security";
  if (pathname.startsWith(ROUTES.ADMIN.SECURITY_ENDPOINT_PROTECTION)) return "Endpoint Protection";
  if (pathname.startsWith(ROUTES.ADMIN.SECURITY)) return "Security Management";
  if (pathname.startsWith(ROUTES.ADMIN.CONFIG_PAYMENT_METHODS)) return "Payment Methods";
  if (pathname.startsWith(ROUTES.ADMIN.CONFIG_SHIPPING)) return "Shipping";
  if (pathname.startsWith(ROUTES.ADMIN.CONFIG_ECOMMERCE)) return "Ecommerce Connections";
  if (pathname.startsWith(ROUTES.ADMIN.CONFIG_THIRD_PARTY)) return "Third-party Sign-in";
  if (pathname.startsWith(ROUTES.ADMIN.CONFIG_SEARCH_DOCUMENTS)) return "Search Documents";
  if (pathname.startsWith(ROUTES.ADMIN.CONFIG_TEMPLATE_ATTRIBUTES)) return "Template Attributes";
  if (pathname.startsWith(ROUTES.ADMIN.CONFIG_INTERNAL_API_OFFERINGS)) return "Product API Import";
  if (pathname.startsWith(ROUTES.ADMIN.CONFIG_INTERNAL_APIS)) return "Internal APIs";
  if (pathname.startsWith(ROUTES.ADMIN.CONFIG_HOOKS)) return "Hooks";
  if (pathname.startsWith(ROUTES.ADMIN.CONFIG)) return "Configuration";
  return "Admin";
}
